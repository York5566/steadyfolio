import { strict as assert } from 'node:assert';
import { writeFile, mkdir } from 'node:fs/promises';
import { defaultConfig, demoSeries } from '../src/core/demo';
import { analyze, makeSnapshot } from '../src/core/engine';
import type { Snapshot } from '../src/core/schema';

const base = process.env.TEST_API_ORIGIN || 'http://127.0.0.1:8787';
const origin = 'http://127.0.0.1:5173';
const snapshot = makeSnapshot(defaultConfig,demoSeries());
const checks: string[] = [];
async function request(path: string, options: RequestInit = {}) {
  return fetch(base + path, {...options,headers:{Origin:origin,'CF-Connecting-IP':'192.0.2.120',...options.headers},redirect:'manual'});
}
const configResponse = await request('/api/config');
assert.equal(configResponse.status,200);
assert.equal((await configResponse.json() as {localDevelopment:boolean}).localDevelopment,true);
checks.push('Explicit loopback development mode');
const created = await request('/api/shares',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({snapshot,token:'local-development'})});
assert.equal(created.status,201,await created.clone().text());
const share = await created.json() as {id:string;deleteToken:string;expiresAt:string};
assert.match(share.id,/^[a-f0-9]{32}$/);assert.match(share.deleteToken,/^[a-f0-9]{64}$/);
checks.push('D1 stores a bounded snapshot and returns independent random read and delete secrets');
const read = await request(`/api/shares/${share.id}`);
assert.equal(read.status,200);assert.equal(read.headers.get('cache-control'),'no-store');assert.match(read.headers.get('x-robots-tag')??'',/noindex/);
const restored = await read.json() as {snapshot:Snapshot};
assert.deepEqual(restored.snapshot,snapshot);assert.deepEqual(analyze(restored.snapshot),analyze(snapshot));
checks.push('Shared input and recomputed results exactly match the original');
const wrongDelete = await request(`/api/shares/${share.id}`,{method:'DELETE',headers:{Authorization:`Bearer ${'0'.repeat(64)}`}});
assert.equal(wrongDelete.status,404);
assert.equal((await request(`/api/shares/${share.id}`)).status,200);
checks.push('Invalid deletion key does not remove a snapshot');
const removed = await request(`/api/shares/${share.id}`,{method:'DELETE',headers:{Authorization:`Bearer ${share.deleteToken}`}});
assert.equal(removed.status,200);
assert.equal((await request(`/api/shares/${share.id}`)).status,404);
checks.push('Revocation immediately removes API access');
const denied = await request('/api/shares',{method:'POST',headers:{Origin:'https://untrusted.example','Content-Type':'application/json'},body:'{}'});
assert.equal(denied.status,403);assert.equal(denied.headers.get('access-control-allow-origin'),null);
checks.push('Untrusted cross-origin writes fail');
const noOrigin = await fetch(base+'/api/shares',{method:'POST',headers:{'Content-Type':'application/json','CF-Connecting-IP':'192.0.2.121'},body:'{}'});
assert.equal(noOrigin.status,403);
checks.push('Missing-origin share writes fail');
const unknown = await request('/api/not-a-route');assert.equal(unknown.status,404);
const longBody = await request('/api/shares',{method:'POST',headers:{'Content-Type':'application/json','CF-Connecting-IP':'192.0.2.122'},body:JSON.stringify({padding:'a'.repeat(540000)})});assert.equal(longBody.status,413);
checks.push('Oversized payload and unknown API paths fail without a valid insert');
const catalog = await request('/api/market');assert.equal(catalog.status,200);
checks.push('Market catalogue API responds');
await mkdir('acceptance',{recursive:true});
await writeFile('acceptance/api-smoke.json',JSON.stringify({testedAt:new Date().toISOString(),scope:'Local Wrangler / real local D1; production Turnstile not exercised',checks},null,2));
console.log(`${checks.length} API acceptance checks passed.`);
